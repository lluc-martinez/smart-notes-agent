import logging
from app.schemas.telegram_schemas import TelegramUpdate
from app.services.llm_router import analyze_intent
from app.services.telegram_client import send_telegram_message
from app.services.db_service import execute_action

# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

async def process_telegram_update(update: TelegramUpdate) -> None:
    """
    Background task to process the incoming Telegram update.
    Extracts text, sends it to the LLM, and replies to the user.
    """
    if not update.message:
        return

    chat_id = update.message.chat.id
    user_name = update.message.from_user.first_name if update.message.from_user else "Unknown"

    if update.message.text:
        user_text = update.message.text
        logger.info(f"Received text from {user_name}: {user_text}")
        
        try:
            # 1. Send the text to the LLM
            logger.info("Analyzing intent with LLM...")
            router_result = await analyze_intent(user_text)
            
            # Print the parsed JSON in the console for debugging
            logger.info(f"LLM parsed result: {router_result.model_dump_json(indent=2)}")
            
            # 2. Reply to the user with the summary generated by the LLM
            await send_telegram_message(chat_id, router_result.reply_summary)
            
            # 3. Save the action to the database
            execute_action(router_result, chat_id, user_name)
            logger.info("Action successfully saved to the database.")
            
            # TODO: Dispatch the action (Database save, Google Calendar API, etc.)
            # dispatcher.handle(router_result, chat_id)
            
        except Exception as e:
            logger.error(f"Error processing message: {e}")
            await send_telegram_message(chat_id, "⚠️ Hi ha hagut un error processant el teu missatge.")

    elif update.message.voice:
        logger.info(f"Received voice message from {user_name}, file_id: {update.message.voice.file_id}")
        await send_telegram_message(chat_id, "⏳ Estic processant el teu àudio...")
